//! Brand assets drawn from the SVGs in `crates/anyfont/assets/brand/`:
//!
//! - `anyfont-icon.svg` (the letter A in its glowing type frame, on the rounded dark tile) is the
//!   program's icon: exe and window icon, title bar, shortcuts and the installer's icon.
//! - `anyfont-logo.svg` (the same frame without the tile) is the logo: About banner, splash screen
//!   and the installer's side picture.
//! - `anyfont-banner.svg` (About box) and `anyfont-splash.svg` (splash screen) are written by this
//!   command from the logo (edit them here, not by hand), then rendered to PNG for the app.
//!
//! Outputs: `assets/anyfont.ico`, `assets/icon-256.png`, `assets/logo.png`, `assets/banner.png`,
//! `assets/splash.png` and `installer/Wizard{Large,Large-dark,Small}-{100..250}.png`.

use crate::svg::{nested, options, render, save_png, split_svg};
use crate::{root, Result};
use image::codecs::ico::{IcoEncoder, IcoFrame};
use image::ExtendedColorType;

/// Sizes stored in the .ico (Windows picks the closest one for each place it shows the icon).
const ICO_SIZES: [u32; 10] = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256];
/// Display scales the installer has a picture for (Setup picks the one that fits the screen).
const SCALES: [u32; 6] = [100, 125, 150, 175, 200, 250];

/// The About box banner: 548×206 like the reference About banner (black, product name in white,
/// the logo at the right).
pub const BANNER_SIZE: (u32, u32) = (548, 206);
/// The splash screen: the same style, larger, with an empty band at the bottom left where the app
/// draws the version and the loading status (`SPLASH_VERSION_AREA`, x/y/width/height).
pub const SPLASH_SIZE: (u32, u32) = (640, 360);
pub const SPLASH_VERSION_AREA: (u32, u32, u32, u32) = (48, 268, 330, 56);

const GENERATED: &str = "<!-- Generated by the xtask brand command (xtask/src/brand.rs) from anyfont-logo.svg; edit it there. -->";

/// The logo placed at (`x`, `y`) with width `w` (keeps its proportions).
fn logo_at(logo: &str, x: f32, y: f32, w: f32, prefix: &str) -> Result<String> {
    let (v, _) = split_svg(logo)?;
    nested(logo, x, y, w, w * v[3] / v[2], prefix)
}

fn banner(logo: &str) -> Result<String> {
    let (w, h) = BANNER_SIZE;
    let logo = logo_at(logo, 352.0, 26.0, 172.0, "logo_")?;
    Ok(format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 {w} {h}" width="{w}" height="{h}">
  {GENERATED}
  <title>AnyFont – About banner</title>
  <rect width="{w}" height="{h}" fill="#000000"/>
  {logo}
  <text x="66" y="118" font-family="Segoe UI" font-weight="600" font-size="62" fill="#ffffff" letter-spacing="-0.5">AnyFont</text>
  <text x="70" y="150" font-family="Segoe UI" font-size="19" fill="#ffffff">Font Manager</text>
</svg>
"##
    ))
}

fn splash(logo: &str) -> Result<String> {
    let (w, h) = SPLASH_SIZE;
    let (vx, vy, vw, vh) = SPLASH_VERSION_AREA;
    let logo = logo_at(logo, 370.0, 40.0, 240.0, "logo_")?;
    Ok(format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 {w} {h}" width="{w}" height="{h}">
  {GENERATED}
  <title>AnyFont – splash screen</title>
  <defs>
    <radialGradient id="sp_glow" cx="500" cy="170" r="330" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#2f8cff" stop-opacity="0.16"/><stop offset="1" stop-color="#2f8cff" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="{w}" height="{h}" fill="#000000"/>
  <rect width="{w}" height="{h}" fill="url(#sp_glow)"/>
  {logo}
  <text x="44" y="164" font-family="Segoe UI" font-weight="600" font-size="76" fill="#ffffff" letter-spacing="-0.5">AnyFont</text>
  <text x="49" y="200" font-family="Segoe UI" font-size="22" fill="#ffffff">Font Manager</text>
  <text x="49" y="228" font-family="Segoe UI" font-size="14" fill="#9aa3b2">Browse, install and organize your fonts</text>
  <!-- Version area: the app draws "Version x.y.z" and the loading status here (left aligned). -->
  <rect id="version-area" x="{vx}" y="{vy}" width="{vw}" height="{vh}" fill="none"/>
  <rect x="0" y="{line}" width="{w}" height="1" fill="#262626"/>
</svg>
"##,
        line = h - 22,
    ))
}

/// The installer's side picture (164×314 at 100%): the logo, the name and a short line on the
/// icon's dark tile colours (or a light version for Windows' light mode).
fn wizard_large(logo: &str, dark: bool) -> Result<String> {
    let (top, mid, bottom, name, line) = if dark {
        ("#232a3c", "#141826", "#0b0e18", "#ffffff", "#9aa3b2")
    } else {
        ("#f7f9fc", "#eaeef5", "#d9e0ea", "#151a26", "#5a6474")
    };
    let glow = if dark { 1.0 } else { 0.55 };
    let logo = logo_at(logo, 10.0, 70.0, 144.0, "logo_")?;
    Ok(format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 164 314" width="164" height="314">
  <defs>
    <linearGradient id="wz_bg" x1="0" y1="0" x2="0.25" y2="1">
      <stop offset="0" stop-color="{top}"/><stop offset="0.4" stop-color="{mid}"/><stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
    <radialGradient id="wz_cyan" cx="110" cy="80" r="120" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#19e3ff" stop-opacity="{c}"/><stop offset="1" stop-color="#19e3ff" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="wz_orange" cx="150" cy="300" r="120" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ff8a1c" stop-opacity="{o}"/><stop offset="1" stop-color="#ff8a1c" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="wz_magenta" cx="10" cy="300" r="110" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#ff2fb4" stop-opacity="{m}"/><stop offset="1" stop-color="#ff2fb4" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="164" height="314" fill="url(#wz_bg)"/>
  <rect width="164" height="314" fill="url(#wz_cyan)"/>
  <rect width="164" height="314" fill="url(#wz_orange)"/>
  <rect width="164" height="314" fill="url(#wz_magenta)"/>
  {logo}
  <text x="82" y="222" text-anchor="middle" font-family="Segoe UI" font-weight="600" font-size="28" fill="{name}">AnyFont</text>
  <text x="82" y="242" text-anchor="middle" font-family="Segoe UI" font-size="11" fill="{line}">Font manager for Windows</text>
</svg>"##,
        c = 0.30 * glow,
        o = 0.35 * glow,
        m = 0.30 * glow,
    ))
}

pub fn run() -> Result<()> {
    let root = root();
    let assets = root.join("crates/anyfont/assets");
    let brand = assets.join("brand");
    let installer = root.join("installer");
    std::fs::create_dir_all(&installer)?;
    let icon = std::fs::read_to_string(brand.join("anyfont-icon.svg"))?;
    let logo = std::fs::read_to_string(brand.join("anyfont-logo.svg"))?;
    let opt = options();

    println!("program icon:");
    let mut frames = vec![];
    for n in ICO_SIZES {
        let img = render(&icon, n, n, &opt)?;
        frames.push(IcoFrame::as_png(img.as_raw(), n, n, ExtendedColorType::Rgba8)?);
    }
    let ico = assets.join("anyfont.ico");
    IcoEncoder::new(std::fs::File::create(&ico)?).encode_images(&frames)?;
    println!("  {} ({} sizes)", ico.strip_prefix(&root).unwrap_or(&ico).display(), frames.len());
    save_png(&render(&icon, 256, 256, &opt)?, &assets.join("icon-256.png"))?;

    println!("logo, About banner, splash screen:");
    let (v, _) = split_svg(&logo)?;
    let w = 1024;
    save_png(&render(&logo, w, (w as f32 * v[3] / v[2]).round() as u32, &opt)?, &assets.join("logo.png"))?;
    let banner = banner(&logo)?;
    let splash = splash(&logo)?;
    for (name, svg) in [("anyfont-banner.svg", &banner), ("anyfont-splash.svg", &splash)] {
        let p = brand.join(name);
        std::fs::write(&p, svg)?;
        println!("  {}", p.strip_prefix(&root).unwrap_or(&p).display());
    }
    // Twice the design size, so they stay sharp at 200% (the app scales them down otherwise).
    let (bw, bh) = BANNER_SIZE;
    save_png(&render(&banner, bw * 2, bh * 2, &opt)?, &assets.join("banner.png"))?;
    let (sw, sh) = SPLASH_SIZE;
    save_png(&render(&splash, sw * 2, sh * 2, &opt)?, &assets.join("splash.png"))?;

    println!("installer pictures:");
    for old in std::fs::read_dir(&installer)? {
        let p = old?.path();
        let name = p.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
        if name.starts_with("Wizard") && name.ends_with(".png") {
            std::fs::remove_file(&p)?;
        }
    }
    let light = wizard_large(&logo, false)?;
    let dark = wizard_large(&logo, true)?;
    for sc in SCALES {
        let (w, h) = ((164 * sc + 50) / 100, (314 * sc + 50) / 100);
        save_png(&render(&light, w, h, &opt)?, &installer.join(format!("WizardLarge-{sc}.png")))?;
        save_png(&render(&dark, w, h, &opt)?, &installer.join(format!("WizardLarge-dark-{sc}.png")))?;
        let n = (55 * sc + 50) / 100;
        save_png(&render(&icon, n, n, &opt)?, &installer.join(format!("WizardSmall-{sc}.png")))?;
    }
    Ok(())
}
